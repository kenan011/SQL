--TASK1

SELECT FIRST_NAME,
       LAST_NAME,
       SALARY,
       CASE WHEN SALARY < 6000 THEN 'Asagi'
            WHEN SALARY BETWEEN 6000 AND 12000 THEN 'Orta'
            ELSE 'Yuksek'
        END AS MAAS_SEVIYYESI
FROM HR.EMPLOYEES;

--TASK2

SELECT FIRST_NAME , JOB_ID ,
       CASE JOB_ID
            WHEN 'IT_PROG' THEN 'Programci'
            WHEN 'SA_REP' THEN 'Satis numayendesi'
            WHEN 'ST_CLERK' THEN 'Anbar iscisi'
            ELSE 'Diger'
        END AS "VEZIFE"
FROM HR.EMPLOYEES;

--TASK3

SELECT FIRST_NAME, COMMISSION_PCT,
       CASE WHEN COMMISSION_PCT IS NULL THEN 'Komissiya yoxdur'
            ELSE 'Komissiya var'
        END AS KOMMISSIYA_STATUSU
FROM HR.EMPLOYEES;

SELECT FIRST_NAME, COMMISSION_PCT,
       NVL2(COMMISSION_PCT,'Komissiya var','Komissiya yoxdur')
FROM HR.EMPLOYEES;
       
--TASK4

SELECT CITY, COUNTRY_ID,
       CASE WHEN COUNTRY_ID IN ('US', 'CA', 'MX', 'BR') THEN 'Amerika'
            WHEN COUNTRY_ID IN ('UK', 'DE', 'IT', 'NL', 'CH') THEN 'Avropa'
            WHEN COUNTRY_ID IN ('JP', 'CN', 'IN', 'SG') THEN 'Asiya'
            ELSE 'Diger'
        END AS QITE
FROM HR.LOCATIONS;

--TASK5

SELECT FIRST_NAME, DEPARTMENT_ID, SALARY,
        CASE DEPARTMENT_ID
            WHEN 80 THEN SALARY * 0.1
            WHEN 60 THEN SALARY * 0.15
            ELSE SALARY * 0.05
        END AS BONUS
FROM HR.EMPLOYEES

--TASK6

--YANLIS SORQU 

SELECT FIRST_NAME, SALARY,
       CASE
           WHEN SALARY > 5000  THEN 'Orta'
           WHEN SALARY > 15000 THEN 'Yuksek'
           ELSE 0
       END AS 'Seviyye'
FROM HR.EMPLOYEES;

--DOGRU SORQU
SELECT FIRST_NAME,SALARY,
       CASE 
           WHEN SALARY > 15000 THEN 'Yuksek'
           WHEN SALARY > 5000 THEN 'Orta'
           ELSE 'Asagi'
        END AS Seviyye
FROM HR.EMPLOYEES;

--SEHVLER
--1 WHENLERIN ARDICILLIQI DUZGUN OLMALI
--2 ELSE QARSISINDA 0 YOX 'Asagi' OLMALI
--3 ALLIASDA SEVIYYE DIRNAQSIZ OLMALI

--TASK7  

SELECT FIRST_NAME , JOB_ID , MANAGER_ID,
        CASE WHEN MANAGER_ID IS NULL THEN 'Direktor'
            WHEN MANAGER_ID = 100 THEN 'Direktorun komandasi'
            WHEN JOB_ID = 'MAN' OR JOB_ID = 'MGR' THEN 'Menecer'
            ELSE 'Isci'
        END AS ROL
FROM HR.EMPLOYEES;

--TASK8

SELECT FIRST_NAME, SALARY, COMMISSION_PCT,
       SALARY * NVL(COMMISSION_PCT,0) * 12 AS ILLIK_KOMISSIYA,
       SALARY * 12 + SALARY * NVL(COMMISSION_PCT,0) * 12 AS ILLIK_GELIR
FROM HR.EMPLOYEES;

--TASK9

SELECT E.FIRST_NAME, J.JOB_TITLE, E.SALARY, J.MIN_SALARY, J.MAX_SALARY,
        CASE WHEN SALARY = MIN_SALARY THEN 'Minumumda'
             WHEN SALARY = MAX_SALARY THEN 'Maximumda'
             WHEN SALARY < (MIN_SALARY+MAX_SALARY)/2 THEN 'Asagi yarida'
             ELSE 'Yuxari yarida'
        END AS MOVQE     
FROM HR.EMPLOYEES E 
JOIN HR.JOBS J
ON E.JOB_ID = E.JOB_ID 

--TASK10 

SELECT E.FIRST_NAME, E.LAST_NAME ,
        NVL2(DEPARTMENT_NAME,DEPARTMENT_NAME,'SOBESIZ') AS SOBE,
        CASE WHEN DEPARTMENT_NAME IS NULL THEN 'Melum deyil'
             WHEN DEPARTMENT_NAME = 'Seatle' THEN 'Bas office'
             ELSE 'Filial'
        END AS OFIS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = E.DEPARTMENT_ID
JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID;
