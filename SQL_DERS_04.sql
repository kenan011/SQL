--SELF JOIN, SUBQUERIES, WINDOW FUNCTIONS

SELECT S.FIRST_NAME, S.SALARY, M.FIRST_NAME AS MENECER_NAME, M.SALARY AS MENECER_SALARY
FROM DEMO_STAFF S
JOIN DEMO_STAFF M
ON S.MANAGER_ID = M.EMPLOYEE_ID 

--SUBQUERIES 
SELECT DEPARTMENT_ID FROM HR.DEPARTMENTS
WHERE DEPARTMENT_NAME IN ('IT','Sales')

SELECT FIRST_NAME, DEPARTMENT_ID FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID FROM HR.DEPARTMENTS
                        WHERE DEPARTMENT_NAME IN ('IT','Sales'))



SELECT AVG(SALARY) 
FROM HR.EMPLOYEES

SELECT FIRST_NAME, DEPARTMENT_ID 
FROM HR.EMPLOYEES
WHERE SALARY > (SELECT AVG(SALARY)
                FROM HR.EMPLOYEES  E
                WHERE E.DEPARTMENT_ID = DEPARTMENT_ID)