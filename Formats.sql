--TASK1

SELECT FIRST_NAME || ' ' || UPPER(LAST_NAME) AS TAM_AD,
        SUBSTR(FIRST_NAME ,1,1) || '.  '  || LAST_NAME AS QISA_AD,
        LOWER(EMAIL || '@COMPANY.COM') AS EMAIL
FROM HR.EMPLOYEES;

--TASK2

SELECT FIRST_NAME,
        TO_CHAR(SALARY,'FM99,999')|| ' AZN' AS MAAS,
        TO_CHAR(SALARY * 12 , '99,999,999.00') AS ILLIK_MAAS
FROM HR.EMPLOYEES
ORDER BY SALARY DESC;
--MAAS STRING FORMATINDADIR ORDER BY QARSISINDA YAZSAQ DUZGUN SIRALANMAYACAQ

--TASK3

SELECT FIRST_NAME,
        TO_CHAR(HIRE_DATE,'DD.MM.YYYY') AS ISE_GIRIS,
        EXTRACT(YEAR FROM HIRE_DATE) AS IL,
        TO_CHAR(HIRE_DATE, 'Month') AS AY_ADI,
        TO_CHAR(HIRE_DATE, 'Day') AS HEFTE_GUNU
FROM HR.EMPLOYEES;

--TASK4

SELECT FIRST_NAME || ' ' || LAST_NAME AS ISCI,
        TO_CHAR(HIRE_DATE, 'DD Month YYYY') AS ISE_GIRIS,
        TRUNC(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12) || ' il '||
        MOD(TRUNC(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)),12) || ' ay ' AS STAJ
FROM HR.EMPLOYEES
ORDER BY MONTHS_BETWEEN(SYSDATE,HIRE_DATE) DESC;

