--YANLIS SORQU

SELECT CONCAT(FIRST_NAME, ' ', LAST_NAME) || ', komissiya: ' || 
NVL(COMMISSION_PCT, 'yoxdur') AS MELUMAT
FROM HR.EMPLOYEES
WHERE TO_CHAR(HIRE_DATE, 'MM') = '3';

--DUZGUN SORQU

SELECT FIRST_NAME || ' ' || LAST_NAME || ', komissiya: ' || 
        NVL(TO_CHAR(COMMISSION_PCT,'0.00'), 'yoxdur') AS MELUMAT
FROM HR.EMPLOYEES
WHERE TO_CHAR(HIRE_DATE, 'MM') = '03';
--SEHVLER
--1 CONCATLA MAX IKI ARQUMENT BIRLESIR 
--2 NVL DAXILINDE IKI MUXTELIF TIP UYUSMUR
--3 MM IKI REQEMLI AY QAYTARIR 3 YOX 03 YAZILMALIDI

--TASK7

SELECT 
    TO_CHAR(HIRE_DATE, 'MM') AS AY_NO,
    TO_CHAR(HIRE_DATE, 'Month') AS AY,
    COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY 
    TO_CHAR(HIRE_DATE, 'MM'),
    TO_CHAR(HIRE_DATE, 'Month')
ORDER BY AY_NO;

--ORDER BY AY YAZSAQ AYLAR TEQVIM SIRASI ILE YOX ELIFBA SIRASI ILE DWZWLERDI

--TASK8 

SELECT EMPLOYEE_ID,
        LOWER(SUBSTR(FIRST_NAME,1,1) || LAST_NAME) || LPAD(EMPLOYEE_ID,4,0) AS LOGIN,
        REPLACE(PHONE_NUMBER,'.','-') AS TELEFON
FROM HR.EMPLOYEES
WHERE LENGTH(LAST_NAME) >= 7;

--TASK9

SELECT TO_CHAR(HIRE_DATE,'YYYY') AS IL,
        COUNT(*) AS ISCI_SAYI,
        TO_CHAR(MIN(HIRE_DATE),'DD.MM.YYYY') AS ILK_TARIX,
        TO_CHAR(MAX(HIRE_DATE),'DD.MM.YYYY') AS SON_TARIX,
        TO_CHAR(AVG(SALARY),'999,999.00') AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY TO_CHAR(HIRE_DATE,'YYYY') 
ORDER BY  TO_CHAR(HIRE_DATE,'YYYY');

