SELECT FIRST_NAME,
        TO_CHAR(HIRE_DATE,'Dy,DD.MM.YYYY') AS ISE_GIRIS,
        CASE 
            WHEN TRIM(TO_CHAR(HIRE_DATE,'DAY')) IN ('SATURDAY','SUNDAY')
                   THEN 'HEFTE SONU'
            ELSE 'IS GUNU'
        END AS GUN_NOVU
FROM HR.EMPLOYEES;
--CASE-in içində TO_CHAR(HIRE_DATE, 'DAY')= 'SATURDAY' YAZSAQ
--DAYDEN QAYDACAQ STRINGDE BOSLUQLAR OLA BILER DEYE DUZGUN ISLEMEYECEK TRIM() ELEMEK LAZMDI

--B

SELECT TRIM(TO_CHAR(HIRE_DATE,'Day')) AS GUN,
        COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY TRIM(TO_CHAR(HIRE_DATE,'Day'))
ORDER BY ISCI_SAYI DESC;

