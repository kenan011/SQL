--TASK1

SELECT DEPARTMENT_ID,
       MAX(SALARY) AS MAKS_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING DEPARTMENT_ID IS NOT NULL
ORDER BY MAKS_MAAS DESC; 

--TASK2 

SELECT LOCATION_ID,
       COUNT(*) AS SOBE_SAYI
FROM HR.DEPARTMENTS
GROUP BY LOCATION_ID
ORDER BY SOBE_SAYI DESC;

--TASK3

SELECT E.FIRST_NAME, E.LAST_NAME, D.DEPARTMENT_NAME
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

--TASK4

SELECT JOB_ID,
       SUM(SALARY) AS UMUMI_MAAS
FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING SUM(SALARY) > 30000;

--TASK5

SELECT DEPARTMENT_ID,
       MIN(SALARY) AS MIN_MAAS
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID 
HAVING MIN(SALARY) > 4000
ORDER BY MIN_MAAS ASC;

--TASK6

SELECT J.JOB_TITLE, 
       ROUND(AVG(E.SALARY),2) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J
ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE
HAVING AVG(SALARY) BETWEEN 6000 AND 12000;

--TASK7 

SELECT J.JOB_TITLE
FROM HR.JOBS J
LEFT JOIN HR.EMPLOYEES E
ON J.JOB_ID = E.JOB_ID
WHERE E.JOB_ID IS NULL;

