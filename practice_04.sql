SELECT DEPARTMENT_ID, MANAGER_ID,
        COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL 
        AND MANAGER_ID IS NOT NULL
GROUP BY DEPARTMENT_ID,MANAGER_ID;
       
--TASK10

SELECT L.CITY,
        SUM(E.SALARY) AS UMUMI_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID 
GROUP BY CITY
HAVING SUM(E.SALARY) > 20000;


--TASK11

SELECT L.CITY,
        COUNT(D.DEPARTMENT_ID) AS SOBE_SAYI
FROM HR.LOCATIONS L
LEFT JOIN HR.DEPARTMENTS D
ON L.LOCATION_ID = D.LOCATION_ID
GROUP BY CITY
ORDER BY SOBE_SAYI DESC;

--TASK12

SELECT D.DEPARTMENT_NAME,
        ROUND(COUNT(E.EMPLOYEE_ID),0) AS ISCI_SAYI,
        ROUND(AVG(E.SALARY),0) AS ORTA_MAAS
FROM HR.DEPARTMENTS D
JOIN HR.EMPLOYEES E
ON D.DEPARTMENT_ID = E.DEPARTMENT_ID 
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(E.EMPLOYEE_ID) > 2;

--TASK13

SELECT J.JOB_TITLE, D.DEPARTMENT_NAME,
        COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI 
FROM HR.JOBS J
JOIN HR.EMPLOYEES E
ON J.JOB_ID = E.JOB_ID
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY JOB_TITLE,DEPARTMENT_NAME
ORDER BY ISCI_SAYI ASC;