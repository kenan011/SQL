SELECT E.FIRST_NAME, E.LAST_NAME,
        M.FIRST_NAME AS MENECER_ADI,
        M.LAST_NAME AS MENECER_SOYADI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M
ON E.EMPLOYEE_ID = M.MANAGER_ID;

