--WINDOW FUNCTIONS
SELECT FIRST_NAME, AVG(SALARY) OVER() FROM HR.EMPLOYEES;

SELECT FIRST_NAME,
        SALARY,
        AVG(SALARY) OVER() AS ORTALAMA_MAAS,
        SALARY - (AVG(SALARY) OVER()) AS FERQ  
FROM HR.EMPLOYEES 


SELECT DEPARTMENT_ID,
        AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID) AS DEP_ORTALAMA_MAAS
FROM HR.EMPLOYEES;



-- DEPARTMENTDEKI ADAMLARIN SAYI 10 DAN COX OLAN DEPARTMENTLERIN ORTALAMA MAASINI VE ISLEYENLERIN SAYINI TAPN

SELECT DEPARTMENT_ID,
        AVG(SALARY)
        COUNT(*) 
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID 
HAVING COUNT(*) > 10;

SELECT FIRST_NAME,DEPARTMENT_ID,
       COUNT(*) OVER(PARTITION BY DEPARTMENT_ID) AS SAY,
       AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID) AS DEP_ORTALAMA_MAAS 
FROM HR.EMPLOYEES 

SELECT * FROM(SELECT FIRST_NAME,DEPARTMENT_ID,
                COUNT(*) OVER(PARTITION BY DEPARTMENT_ID) AS SAY,
                AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID) AS DEP_ORTALAMA_MAAS 
              FROM HR.EMPLOYEES )
WHERE SAY > 10;


-- RANK FUNCTIONS,RANK,DENSE RANK,ROW NUMBER

SELECT  FIRST_NAME,SALARY,
        RANK() OVER( ORDER BY SALARY) AS SIRA
FROM HR.EMPLOYEES;

SELECT  FIRST_NAME,SALARY,
        DENSE_RANK() OVER( ORDER BY SALARY) AS SIRA
FROM HR.EMPLOYEES;

SELECT  FIRST_NAME,SALARY,
        ROW_NUMBER() OVER( ORDER BY SALARY) AS SIRA
FROM HR.EMPLOYEES;

SELECT * FROM(SELECT  FIRST_NAME,SALARY,
                       DENSE_RANK() OVER( ORDER BY SALARY) AS SIRA
             FROM HR.EMPLOYEES)
WHERE SIRA = 20

