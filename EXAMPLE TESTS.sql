SELECT E.FIRST_NAME,E.SALARY,
        NVL(M.FIRST_NAME,'Menecer yoxdur') AS MENECER,
        NVL(M.SALARY - E.SALARY,0) AS FERQ 
FROM HR.EMPLOYEES E 
LEFT JOIN HR.EMPLOYEES M 
ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE E.SALARY > 15000;

