SELECT JOB_ID, FIRST_NAME, SALARY, VEZIFE_ORTASI
FROM (SELECT JOB_ID,
             FIRST_NAME,
             SALARY,
             ROUND(AVG(SALARY) OVER (PARTITION BY JOB_ID))         AS VEZIFE_ORTASI,
             RANK() OVER (PARTITION BY JOB_ID ORDER BY SALARY ASC) AS YER
      FROM HR.EMPLOYEES)
WHERE YER = 1;


