SELECT FIRST_NAME,
        TO_CHAR(HIRE_DATE,'FMDD Month YYYY') AS ISE_GIRIS,
        EXTRACT(YEAR FROM HIRE_DATE) AS IL,
        TRUNC(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)) AS AY_SAYI
FROM HR.EMPLOYEES
WHERE HIRE_DATE < TO_DATE('01.01.2005','DD.MM.YYYY')
ORDER BY HIRE_DATE;

