SELECT FIRST_NAME,
       NVL(MANAGER_ID,0) AS MENECER_NO,
       CASE WHEN COMMISSION_PCT IS NULL THEN 'Yoxdur'
            WHEN COMMISSION_PCT >= 0.3 THEN 'Yuksek'
            ELSE 'Var'
       END AS KOMISIYA_VEZIYETI
FROM HR.EMPLOYEES;

--SUAL3

SELECT L.CITY,
        COUNT(*) AS ISCI_SAYI
FROM HR.LOCATIONS L 
JOIN HR.DEPARTMENTS D 
ON L.LOCATION_ID = D.LOCATION_ID 
JOIN HR.EMPLOYEES E
ON D.DEPARTMENT_ID = E.DEPARTMENT_ID 
GROUP BY L.CITY
HAVING COUNT(*) > 3
ORDER BY ISCI_SAYI DESC;

