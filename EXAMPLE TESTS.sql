SELECT SUBSTR(FIRST_NAME,1,1) || '. ' || LAST_NAME AS QISA_AD,
       DEPARTMENT_ID,
       LENGTH(LAST_NAME) AS SOYAD_UZUNLUQU
FROM HR.EMPLOYEES
WHERE FIRST_NAME LIKE 'A%'
      AND DEPARTMENT_ID IN (60,80,100)
ORDER BY LAST_NAME;

